/**
 * « Classe 7 » : un thème, 7 propositions tirées au hasard dans une liste plus longue,
 * à remettre dans le bon ordre. Chaque rang d'écart coûte des points.
 *
 * `value` sert uniquement à trier (jamais affichée telle quelle) ; `show` est affiché à la révélation.
 * `dir` : 'asc' → la plus petite valeur en 1er ; 'desc' → la plus grande en 1er.
 * Deux propositions de même valeur ne sont jamais tirées ensemble.
 */
export interface OrderItem {
  label: string;
  value: number | string;
  show?: string;
}

export interface OrderTheme {
  id: string;
  q: string;
  /** Libellés des deux extrémités (ex : « Plus ancien » / « Plus récent ») */
  top: string;
  bottom: string;
  dir: 'asc' | 'desc';
  items: OrderItem[];
  /** Thème rare (ordre alphabétique…) : tiré moins souvent */
  rare?: boolean;
}

const it = (label: string, value: number | string, show?: string): OrderItem => ({ label, value, show });
/** Date « AAAAMMJJ » → affichage « 12 mars 1985 » */
const MONTHS = ['janv.', 'févr.', 'mars', 'avr.', 'mai', 'juin', 'juil.', 'août', 'sept.', 'oct.', 'nov.', 'déc.'];
const born = (label: string, ymd: string): OrderItem => {
  const [y, m, d] = ymd.split('-').map(Number);
  return { label, value: y * 10000 + m * 100 + d, show: `né(e) le ${d} ${MONTHS[m - 1]} ${y}` };
};
const yr = (label: string, year: number): OrderItem => ({ label, value: year, show: year < 0 ? `vers ${-year} av. J.-C.` : String(year) });
const word = (w: string): OrderItem => ({ label: w, value: w });

