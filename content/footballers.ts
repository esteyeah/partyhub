/** Saison de référence pour calculer l'âge */
const SEASON_YEAR = 2026;

const ROLE_TO_POS = (role: string): FootPos => (role === 'GB' ? 'GK' : role.startsWith('D') ? 'DEF' : role.startsWith('M') ? 'MID' : 'ATT');

/** Coefficient d'âge : les jeunes à potentiel coûtent plus cher, les anciens un peu moins (mais restent chers s'ils sont bons). */
export const ageFactor = (age?: number) =>
  age === undefined ? 1 : age <= 21 ? 1.3 : age <= 24 ? 1.15 : age <= 28 ? 1 : age <= 30 ? 0.9 : age <= 32 ? 0.8 : age <= 34 ? 0.7 : 0.6;

/** Prix (M€) : d'abord la note (~3 M€ à 70, ~20 M€ à 80, ~120 M€ à 90), puis l'âge */
export const priceFor = (rating: number, age?: number) => Math.max(1, Math.round(3 * Math.exp((rating - 70) * 0.185) * ageFactor(age)));

const slug = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function toFootballer([name, nat, club, league, rating, roles]: Row, surprise = false): Footballer {
  const list = roles.split('/');
  const year = BIRTH_YEARS[name];
  const age = year ? SEASON_YEAR - year : undefined;
  return {
    id: (surprise ? 'flop-' : '') + slug(name),
    name,
    pos: ROLE_TO_POS(list[0]),
    roles: list,
    nat,
    flag: FLAGS[nat] ?? '🏳️',
    club,
    league,
    rating,
    age,
    price: surprise ? 0 : priceFor(rating, age),
  };
}

