export type PixelCategory = 'celeb' | 'game' | 'film';

export interface PixelItem {
  /** Réponse affichée (en français) */
  name: string;
  /** Titre exact de l'article sur en.wikipedia.org */
  wiki: string;
  cat: PixelCategory;
  /** Autres réponses acceptées (nom de famille, titre original…) */
  aliases?: string[];
}

